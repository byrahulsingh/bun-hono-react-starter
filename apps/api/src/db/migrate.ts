import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { migrate } from 'drizzle-orm/bun-sql/postgres/migrator';

import { syncDatabaseAccess } from '#/db/access';
import { runBackfills } from '#/db/backfill';
import { syncCatalog } from '#/db/catalog';
import { logger } from '#/libs/logger';

import { client, db, disconnectDb } from './db';

// Any fixed number; it only has to be the same for every process that migrates.
const MIGRATION_LOCK_ID = 872_401;

const migrationsFolder = join(import.meta.dir, '../../drizzle');

/**
 * The whole deploy-time database step, in order:
 *   1. migrations generated by drizzle-kit from the schema
 *   2. roles and grants, derived from the schema (access.ts)
 *   3. catalogs from code: lookups, permissions, built-in roles (catalog.ts)
 *   4. backfills: data for columns that existing installs lack (backfill.ts)
 *
 * Under an advisory lock: if several containers start at once, one does the
 * work and the others wait, then find nothing left to do.
 */
export async function runMigrations() {
  // A fresh project has no migrations until the first `db:generate`. That is
  // not a failure: the deploy step that runs this must still pass.
  if (!existsSync(migrationsFolder)) {
    logger.db.warn({ migrationsFolder }, 'No migrations folder yet — nothing to apply');
    return;
  }

  const lock = await client.reserve();
  try {
    await lock`select pg_advisory_lock(${MIGRATION_LOCK_ID})`;
    await migrate(db, { migrationsFolder });
    logger.db.info('Migrations applied');
    await db.transaction(async (tx) => {
      await syncDatabaseAccess(tx);
      await syncCatalog(tx);
      const filled = await runBackfills(tx);
      if (Object.values(filled).some((v) => v !== null)) logger.db.info(filled, 'Backfilled existing data');
    });
    logger.db.info('Database roles, grants and catalog in sync');
  } finally {
    await lock`select pg_advisory_unlock(${MIGRATION_LOCK_ID})`;
    lock.release();
  }
}

if (import.meta.main) {
  try {
    await runMigrations();
  } finally {
    await disconnectDb();
  }
}
